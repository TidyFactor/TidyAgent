/**
 * Tidy Task Brief Generator
 * Synthesizes self-contained, context-rich task briefs for AI agents,
 * blending 3-Ring Cognitive Context with Skill-specific operational boundaries.
 */

const fs = require('fs');
const path = require('path');
const { getDb } = require('./db');
const { recallMemory } = require('./memory');
const { getTask, updateTaskBrief } = require('./apps');
const { getSubagent } = require('./subagents');
const { getRegisteredSkill } = require('./skills-loader');

/**
 * Generate a complete, self-contained Task Brief
 */
function generateTaskBrief({
  taskId = null,
  taskTitle = '',
  taskDescription = '',
  agentName = 'coder',
  domain = 'general',
  verificationGates = [],
  outputPath = null
}) {
  const db = getDb();
  let task = null;

  if (taskId) {
    task = getTask(taskId);
    if (!task) {
      throw new Error(`Task with ID "${taskId}" not found.`);
    }
    taskTitle = task.title;
    taskDescription = task.description || '';
    domain = task.domain || domain;
    if (task.assigned_agent) agentName = task.assigned_agent;
  }

  if (!taskTitle) {
    throw new Error('taskTitle or a valid taskId is required to generate a brief.');
  }

  // Ring 0: User Profile & Persona
  const profile = db.prepare("SELECT * FROM user_profile WHERE id = 'primary'").get() || {
    user_name: 'Founder',
    assistant_name: 'Tidy',
    locale: 'en',
    tone: 'concise_expert'
  };

  // Ring 1: Active Workspace Context
  const activeCtx = db.prepare('SELECT * FROM contexts WHERE is_active = 1 LIMIT 1').get() || {
    id: 'ctx_general',
    name: 'General Workspace',
    domain
  };

  // Ring 2: Recall Memory matching task
  const query = `${taskTitle} ${taskDescription}`;
  const memories = recallMemory({ query, limit: 5, contextId: activeCtx.id });

  // Retrieve Agent / Skill Details
  const agent = getSubagent(agentName) || {
    name: agentName,
    role: 'Autonomous Assistant',
    description: 'General execution agent',
    system_prompt: ''
  };

  const skill = getRegisteredSkill(agentName);

  // Construct Verification Gates
  const gates = verificationGates.length > 0
    ? verificationGates
    : [
        'Deterministic syntax check / compile check',
        'Run existing automated test suites',
        'Verify zero undocumented behavioral drift'
      ];

  const timestamp = new Date().toISOString();

  // Generate Markdown Task Brief
  const briefMarkdown = `# TASK BRIEF: ${taskTitle}
<!-- Generated by Tidy Cognitive OS on ${timestamp} -->
<!-- Assigned Agent: @${agent.name} | Domain: ${domain.toUpperCase()} -->

## 1. Goal & Mission
${taskDescription || taskTitle}

- **Priority**: ${task ? task.priority.toUpperCase() : 'MEDIUM'}
- **Domain**: ${domain}
- **Assigned Subagent**: @${agent.name} (${agent.role})

---

## 2. Context & Identity Layer (3-Ring Context)
### Ring 0: Principal & Persona
- **Principal**: ${profile.user_name}
- **Assistant**: ${profile.assistant_name}
- **Language / Tone**: ${profile.locale} (${profile.tone})

### Ring 1: Workspace & Operational Domain
- **Active Workspace**: ${activeCtx.name} (\`${activeCtx.domain}\`)

### Ring 2: Active Memory & Established Decisions
${
  memories.length > 0
    ? memories.map(m => `- [${m.category.toUpperCase()}] ${m.content}`).join('\n')
    : '- No prior conflicting memory entries found for this task query.'
}

---

## 3. Operational Rules & Boundaries (@${agent.name})
${
  skill
    ? `Powered by skill: **${skill.name}**\nPath: \`${skill.skill_path}\`\n\n${agent.system_prompt}`
    : agent.system_prompt
}

### Execution Constraints:
1. **Self-Containment**: Do not assume access to interactive chat history. Rely on this brief.
2. **Deterministic Output**: Deliver pure code, configuration, or copy without conversational filler.
3. **No Unapproved Commits**: If running in a git repository, leave changes unstaged for review.

---

## 4. Verification Gates
Before marking this task complete, satisfy all verification gates:
${gates.map((g, idx) => `${idx + 1}. [ ] ${g}`).join('\n')}

---
*End of Task Brief · Tidy Sovereign Assistant*
`;

  // Update task in DB if taskId was supplied
  if (taskId) {
    updateTaskBrief(taskId, briefMarkdown);
  }

  // Save to file if outputPath requested
  if (outputPath) {
    const resolvedOut = path.resolve(outputPath);
    const outDir = path.dirname(resolvedOut);
    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }
    fs.writeFileSync(resolvedOut, briefMarkdown, 'utf8');
  }

  return {
    taskId,
    title: taskTitle,
    agent: agent.name,
    domain,
    briefMarkdown,
    outputPath: outputPath ? path.resolve(outputPath) : null
  };
}

module.exports = {
  generateTaskBrief
};
